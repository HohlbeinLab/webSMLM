#!/usr/bin/env node
// Picasso localization files (.hdf5 + optional .yaml) through Load data.
//   1. Fixtures written with h5py exactly as Picasso's save_locs() does
//      (create_dataset('locs', records) + a /metadata JSON string): 2D, 3D
//      (z, lpz in nm), picked (int32 group), and a pre-0.11 file with only a
//      .yaml. Every loaded value is compared with h5py's own read.
//   2. A pandas.to_hdf() file is refused with a message naming the problem.
//   3. Picasso's own sample files (dataset picassoSamples, optional) load
//      and match h5py.
// Needs python3 with h5py (and numpy) for the reference reads; skips otherwise.
import { launchPage } from '../lib/launch.mjs';
import { resolveDatasetFile } from '../lib/data.mjs';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, basename } from 'node:path';
import assert from 'node:assert/strict';

const python = process.env.PYTHON || 'python3';
try { execFileSync(python, ['-c', 'import h5py, numpy'], { stdio: 'ignore' }); }
catch { console.log('Skipping — python3 with h5py/numpy not found (set PYTHON=<path> to a Python that has them).'); process.exit(0); }

const dir = mkdtempSync(join(tmpdir(), 'websmlm-picasso-'));
const py = (code, ...args) => execFileSync(python, ['-c', code, ...args], { encoding: 'utf8', maxBuffer: 1 << 28 });

// ---- fixtures, written the way picasso.io.save_locs() writes them ----
py(`
import h5py, numpy as np, json, sys, os
d = sys.argv[1]
rng = np.random.default_rng(7)
def locs(n, extra=()):
    dt = [('frame','<u4'),('x','<f4'),('y','<f4'),('photons','<f4'),('sx','<f4'),('sy','<f4'),('bg','<f4'),('lpx','<f4'),('lpy','<f4'),('net_gradient','<f4'),('ellipticity','<f4')] + list(extra)
    a = np.zeros(n, dtype=dt)
    a['frame'] = rng.integers(0, 300, n); a['x'] = rng.uniform(0.5, 63.5, n); a['y'] = rng.uniform(0.5, 47.5, n)
    a['photons'] = rng.uniform(300, 9000, n); a['sx'] = rng.uniform(0.8, 1.4, n); a['sy'] = rng.uniform(0.8, 1.4, n)
    a['bg'] = rng.uniform(2, 60, n); a['lpx'] = rng.uniform(0.03, 0.3, n); a['lpy'] = rng.uniform(0.03, 0.3, n)
    a['net_gradient'] = rng.uniform(3000, 30000, n); a['ellipticity'] = rng.uniform(0, 0.4, n)
    for name, t in extra:
        a[name] = rng.integers(0, 50, n) if t.startswith('<i') else rng.uniform(-500, 500, n)
    return a
info = [{"Frames": 300, "Width": 64, "Height": 48, "Byte Order": "<"}, {"Generated by": "Picasso Localize", "Pixelsize": 117}]
def save(name, a, meta=True):
    with h5py.File(os.path.join(d, name), 'w') as f:
        f.create_dataset('locs', data=a)
        if meta: f.create_dataset('metadata', data=json.dumps(info))
save('2d.hdf5', locs(2000))
save('3d.hdf5', locs(1500, [('z','<f4'),('lpz','<f4'),('d_zcalib','<f4')]))
save('picked.hdf5', locs(800, [('group','<i4')]))
save('old.hdf5', locs(500), meta=False)
open(os.path.join(d, 'old.yaml'), 'w').write('Frames: 300\\nWidth: 64\\nHeight: 48\\nByte Order: <\\nCamera:\\n  name: test\\n---\\nGenerated by: Picasso Localize\\nPixelsize: 104\\nBox Size: 7\\nZ Calibration:\\n- 1.0\\n- 2.0\\n')
try:
    import pandas as pd, tables
    pd.DataFrame(locs(100)).to_hdf(os.path.join(d, 'pandas.hdf5'), key='locs', mode='w', format='fixed')
except Exception:
    pass
`, dir);

// Reference read with h5py: every column of every row.
const reference = path => JSON.parse(py(`
import h5py, json, sys
with h5py.File(sys.argv[1], 'r') as f:
    a = f['locs'][()]
    print(json.dumps({k: a[k].astype(float).tolist() for k in a.dtype.names}))
`, path));

const { browser, page } = await launchPage({ headless: true });
try {
  await page.evaluate(() => { $('pxnm').value = 160; });
  const load = async (paths, n) => {
    await page.evaluate(() => { window.__logLen = $('logText').textContent.length; lastResult = null; });
    await page.setInputFiles('#file', paths);
    await page.waitForFunction(() => (lastResult && lastResult.fromCsv) || /Load data failed|Load data:/.test($('logText').textContent.slice(window.__logLen)), null, { timeout: 60000 });
    return page.evaluate(() => ({ log: $('logText').textContent.slice(window.__logLen), px: paramValue('pxnm'),
      r: lastResult && { n: lastResult.locs.length, w: lastResult.w, h: lastResult.h, px: lastResult.px, coordsInPx: lastResult.coordsInPx } }));
  };
  const compare = async (path, name) => {
    const ref = reference(path), n = ref.x.length;
    const got = await page.evaluate(() => { const f = k => lastResult.locs.map(L => L[k] === undefined ? null : L[k]);
      return { frame: f('frame'), x: f('x'), y: f('y'), photons: f('photons'), bg: f('bg'), sx: f('sx'), sy: f('sy'), lpx: f('lpx'), lpy: f('lpy'), z: f('z'), lpz: f('lpz'), sigma: f('sigma') }; });
    for (const k of ['frame', 'x', 'y', 'photons', 'bg', 'sx', 'sy', 'lpx', 'lpy', 'z', 'lpz']) {
      if (!ref[k]) { assert.ok(got[k].every(v => v === null), `${name}: ${k} should be absent`); continue; }
      for (let i = 0; i < n; i++) {
        const want = k === 'frame' ? Math.trunc(ref[k][i]) : ref[k][i];
        assert.equal(got[k][i], want, `${name} row ${i} ${k}: ${got[k][i]} vs ${want}`);
      }
    }
    for (let i = 0; i < n; i++) assert.ok(Math.abs(got.sigma[i] - Math.sqrt(ref.sx[i] * ref.sy[i])) < 1e-12, `${name} row ${i} sigma`);
    return n;
  };

  for (const [name, pxWant] of [['2d', 117], ['3d', 117], ['picked', 117]]) {
    const out = await load(join(dir, name + '.hdf5'));
    assert.ok(out.r, `${name}: not loaded — ${out.log}`);
    assert.equal(out.px, pxWant, `${name}: Pixel size from metadata`);
    assert.deepEqual([out.r.w, out.r.h, out.r.coordsInPx], [64, 48, true]);
    const n = await compare(join(dir, name + '.hdf5'), name);
    console.log(`  ${name}: ${n} rows identical to h5py, Pixel size ${out.px} nm and field 64×48 from /metadata`);
  }
  if (true) {
    const out = await load([join(dir, 'old.hdf5'), join(dir, 'old.yaml')]);
    assert.ok(out.r && out.px === 104 && out.r.w === 64, `old + yaml: ${JSON.stringify(out)}`);
    await compare(join(dir, 'old.hdf5'), 'old');
    const bare = await load(join(dir, 'old.hdf5'));
    assert.ok(bare.r && /no metadata/.test(bare.log), 'old without yaml should warn');
    console.log('  pre-0.11 file: metadata from the .yaml picked with it (Pixel size 104 nm); warned without it');
  }
  // Pixel size changes don't move px-anchored positions.
  const moved = await page.evaluate(() => { const x = lastResult.locs[0].x; $('pxnm').value = 250; $('pxnm').dispatchEvent(new Event('change')); return [x, lastResult.locs[0].x, lastResult.px]; });
  assert.deepEqual([moved[1], moved[2]], [moved[0], 250]);
  console.log('  Pixel size change: positions unchanged (camera px), lastResult.px updated');
  if (existsSync(join(dir, 'pandas.hdf5'))) {
    const out = await load(join(dir, 'pandas.hdf5'));
    assert.ok(!out.r && /pandas\.to_hdf/.test(out.log), out.log);
    console.log('  pandas.to_hdf() file: refused with a clear message');
  } else console.log('  pandas.to_hdf() check skipped (pandas/tables not installed)');

  // Headless: analyze() takes a Picasso file like a .csv.
  const head = await page.evaluate(async b64 => {
    const r = await window.webSMLM.analyze({ file: new File([Uint8Array.from(atob(b64), c => c.charCodeAt(0))], '2d.hdf5'), pxnm: 117 });
    return r.locs ? r.locs.length : null;
  }, readFileSync(join(dir, '2d.hdf5')).toString('base64'));
  assert.equal(head, 2000);
  console.log(`  analyze({file:'2d.hdf5'}): ${head} locs`);

  // Picasso's own sample files (optional download: npm --prefix tools run data:download:picasso-samples).
  let nSamples = 0;
  for (const role of ['raw_movie_locs', 'raw_movie_locs_picked', 'egfr_mols', 'testdata_locs']) {
    const h5 = await resolveDatasetFile('picassoSamples', role);
    if (!h5) continue;
    const yaml = h5.replace(/\.hdf5$/, '.yaml');
    const out = await load(existsSync(yaml) ? [h5, yaml] : h5);
    assert.ok(out.r, `${basename(h5)}: ${out.log}`);
    await compare(h5, basename(h5));
    nSamples++;
  }
  console.log(nSamples ? `  Picasso sample files: ${nSamples} loaded, identical to h5py` : '  Picasso sample files: skipped (not downloaded)');
  console.log('Picasso HDF5: PASS');
} finally { await browser.close(); }
